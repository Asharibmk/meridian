"""
build.py: makes MERIDIAN open with a double-click (no server needed).

Browsers refuse to load ES modules and JSON via fetch() from file:// URLs,
so this script produces two plain files that index.html loads instead:

  data/data.js            all four JSON datasets as window.MERIDIAN_DATA
  js/meridian.bundle.js   js/util.js + js/charts/*.js + js/main.js in one script

Edit the source files in js/ as usual, then re-run:

    python3 build.py        (or: python build.py on Windows)

Pure standard library. No Node, no npm.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# Dependency order: util first, charts next, main last.
MODULES = [
    "js/util.js",
    "js/charts/race.js",
    "js/charts/map.js",
    "js/charts/trajectory.js",
    "js/charts/beeswarm.js",
    "js/charts/bump.js",
    "js/charts/trellis.js",
    "js/main.js",
]

IMPORT_RE = re.compile(r'import\s*\{([^}]*)\}\s*from\s*["\']([^"\']+)["\'];?', re.S)
EXPORT_DECL_RE = re.compile(r'^export\s+(async\s+function|function|const|let|var|class)\s+([A-Za-z_$][\w$]*)', re.M)


def module_id(path: Path) -> str:
    rel = path.relative_to(ROOT).with_suffix("").as_posix()
    return "__m_" + re.sub(r"\W", "_", rel)


def build_data():
    names = ["gapminder", "by_year", "countries", "world_topo"]
    bundle = {}
    for n in names:
        with open(ROOT / "data" / f"{n}.json", encoding="utf-8") as f:
            bundle[n] = json.load(f)
    out = ROOT / "data" / "data.js"
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py. Do not edit by hand.\n")
        f.write("window.MERIDIAN_DATA = ")
        json.dump(bundle, f, separators=(",", ":"))
        f.write(";\n")
    print(f"  wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")


def build_js():
    parts = [
        "// Generated by build.py from the ES modules in js/. Do not edit by hand.\n",
        "(async () => {\n\"use strict\";\n",
    ]
    for rel in MODULES:
        path = ROOT / rel
        src = path.read_text(encoding="utf-8")

        def repl_import(m, here=path):
            names = " ".join(m.group(1).split())
            target = (here.parent / m.group(2)).resolve()
            if "default" in names or " as " in names:
                raise SystemExit(f"build.py: unsupported import form in {rel}: {m.group(0)}")
            return f"const {{ {names} }} = {module_id(target)};"

        src = IMPORT_RE.sub(repl_import, src)
        if re.search(r"^\s*(import|export)\b(?!\s+(async\s+)?(function|const|let|var|class)\b)", src, re.M):
            raise SystemExit(f"build.py: unsupported import/export syntax left in {rel}")
        exports = [m.group(2) for m in EXPORT_DECL_RE.finditer(src)]
        src = EXPORT_DECL_RE.sub(lambda m: f"{m.group(1)} {m.group(2)}", src)

        is_async = re.search(r"^\s*(const|let|var)?[^\n]*\bawait\b", src, re.M) and rel == "js/main.js"
        opener = "await (async () => {" if is_async else "(() => {"
        parts.append(f"\n// ---- {rel} ----\nconst {module_id(path)} = {opener}\n")
        parts.append(src)
        parts.append(f"\nreturn {{ {', '.join(exports)} }};\n}})();\n")
    parts.append("\n})().catch((e) => console.error('[MERIDIAN]', e));\n")

    out = ROOT / "js" / "meridian.bundle.js"
    out.write_text("".join(parts), encoding="utf-8")
    print(f"  wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    print("Building MERIDIAN")
    build_data()
    build_js()
    print("Done. Open index.html directly, or serve the folder over HTTP.")
